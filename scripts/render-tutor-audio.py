"""Render the built-in tutor recordings with the same curriculum text as the site.

Setup: pip install kokoro-onnx==0.5.0 onnxruntime==1.32.0 lameenc==1.9.0
Download kokoro-v1.0.int8.onnx and voices-v1.0.bin from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
Run: python scripts/render-tutor-audio.py /path/to/model-files

Only the MP3s and the generated text-to-recording catalog ship to learners.
Use --catalog-only to check the vocabulary map without installing TTS dependencies.
Use --lines-only to refresh greetings and coaching lines without re-rendering lessons.
"""
import argparse
import json
import subprocess
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "tutor-audio"
PAUSE_SECONDS = {"nyx": 0.85, "roxy": 0.35, "selene": 0.70, "ivy": 0.50}
COACH_CUES = {"greeting", "correct", "personal", "retry", "readingPerfect", "readingReview", "deckDone"}


def collect_text():
    script = """
    const fs = require('node:fs'), vm = require('node:vm');
    const data = vm.runInNewContext(fs.readFileSync('curriculum.js', 'utf8') +
        '; [RAW_VOCABULARY_DB, RAW_BRITISH_DB]');
    const tutors = vm.runInNewContext(fs.readFileSync('assets/tutor-lines.js', 'utf8') +
        '; [TUTOR_LINES, tutorVoices]');
    process.stdout.write(JSON.stringify([...data, ...tutors]));
    """
    words, expressions, lines, profiles = json.loads(subprocess.check_output(["node", "-e", script], cwd=ROOT))
    clips = {}
    for item in words:
        word, example, identifier = item["word"], item["example"], item["id"]
        if example.count(word) != 1:
            raise ValueError(f"{identifier}: expected one exact gap")
        clips[word] = identifier + "-word"
        clips[example] = identifier + "-example"
        clips[example.replace(word, "blank", 1)] = identifier + "-blank"
    for item in expressions:
        clips[item["phrase"]] = item["id"] + "-expression"
        clips[item["example"]] = item["id"] + "-dialogue"
    if lines.keys() != profiles.keys() or lines.keys() != PAUSE_SECONDS.keys():
        raise ValueError("The script must include each tutor")
    for tutor, cues in lines.items():
        if cues.keys() != COACH_CUES:
            raise ValueError(f"{tutor}: expected the seven coach cues")
        for cue, beats in cues.items():
            if not isinstance(beats, list) or not beats or not all(isinstance(s, str) and s.strip() for s in beats):
                raise ValueError(f"{tutor}/{cue}: expected one or more nonempty utterances")
    return clips, lines, profiles


def write_catalog(clips):
    entries = ",\n".join("    " + json.dumps(pair, ensure_ascii=False) for pair in clips.items())
    header = "// Generated by scripts/render-tutor-audio.py from the curriculum.\n"
    catalog = f"const TUTOR_AUDIO_CLIPS = new Map([\n{entries}\n]);\n"
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "catalog.js").write_text(header + catalog)


def load_model(directory, threads):
    import onnxruntime as ort
    from kokoro_onnx import Kokoro
    options = ort.SessionOptions()
    options.intra_op_num_threads = threads
    options.inter_op_num_threads = 1
    options.add_session_config_entry("session.intra_op.allow_spinning", "0")
    options.log_severity_level = 3
    session = ort.InferenceSession(str(directory / "kokoro-v1.0.int8.onnx"),
                                   sess_options=options, providers=["CPUExecutionProvider"])
    global model
    model = Kokoro.from_session(session, str(directory / "voices-v1.0.bin"))


def render(job):
    import lameenc
    import numpy as np
    path, utterances, voice, speed, lang, pause = job
    parts = []
    for text in utterances:
        samples, rate = model.create(text, voice=voice, speed=speed, lang=lang)
        if len(samples) < 0.15 * rate or not np.isfinite(samples).all() or np.max(np.abs(samples)) < 0.02:
            raise ValueError(f"Empty or invalid audio for {path}: {text}")
        if parts:
            parts.append(np.zeros(round(rate * pause), dtype=samples.dtype))
        parts.append(samples)
    samples = np.concatenate(parts) if len(parts) > 1 else parts[0]
    pcm = (np.clip(samples, -1.0, 1.0) * 32767.0).astype("<i2").tobytes()
    encoder = lameenc.Encoder()
    encoder.set_channels(1)
    encoder.set_bit_rate(64)
    encoder.set_quality(2)
    encoder.set_in_sample_rate(rate)
    audio = encoder.encode(pcm) + encoder.flush()
    temporary = path.with_suffix(".mp3.tmp")
    temporary.write_bytes(audio)
    temporary.replace(path)
    return round(len(samples) / rate, 3)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("models", type=Path, nargs="?")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--catalog-only", action="store_true")
    mode.add_argument("--lines-only", action="store_true")
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--threads", type=int, default=2)
    args = parser.parse_args()
    clips, lines, profiles = collect_text()
    write_catalog(clips)
    if args.catalog_only:
        return
    if not args.models:
        parser.error("provide the folder containing the downloaded model and voices")
    jobs = []
    for tutor, profile in profiles.items():
        speed = profile["speed"]
        coach_speed = speed * 0.95 if tutor == "nyx" else speed
        for accent, lang in [("uk", "en-gb"), ("us", "en-us")]:
            voice = profile[accent]
            folder = OUTPUT / tutor / accent
            folder.mkdir(parents=True, exist_ok=True)
            for cue, beats in lines[tutor].items():
                stem = "greeting" if cue == "greeting" else "coach-" + cue
                jobs.append((folder / (stem + ".mp3"), beats, voice, coach_speed, lang, PAUSE_SECONDS[tutor]))
            if not args.lines_only:
                for text, stem in clips.items():
                    jobs.append((folder / (stem + ".mp3"), [text], voice, speed, lang, 0))
    with ProcessPoolExecutor(max_workers=args.jobs, initializer=load_model,
                             initargs=(args.models, args.threads)) as workers:
        for index, duration in enumerate(workers.map(render, jobs), start=1):
            if index % 16 == 0 or index == len(jobs):
                print(f"{index}/{len(jobs)} recordings complete", flush=True)


if __name__ == "__main__":
    main()
